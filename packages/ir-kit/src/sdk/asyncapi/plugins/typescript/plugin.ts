import { basename } from "node:path";

import { createClient } from "@hey-api/openapi-ts";

import { asyncapiSchemas, schemaRef } from "../../../../ir/asyncapi.js";
import { definePluginConfig } from "../../plugin.js";

import { defaultConfig } from "./config.js";
import type {
  TypescriptApi,
  TypescriptPluginConfig,
  TypescriptResolvedConfig,
} from "./types.js";

const HEADER = "// AUTO-GENERATED by ir-kit/sdk/asyncapi — do not hand-edit.";

/**
 * Emit TS types for every message payload and named component schema.
 *
 * Payloads are JSON Schema, so they go to Hey API's `@hey-api/typescript` as
 * the `components.schemas` of an OpenAPI 3.1 document.
 */
export const typescript = definePluginConfig<
  "typescript",
  TypescriptPluginConfig,
  TypescriptResolvedConfig,
  MessageTypeRegistry
>({
  name: "typescript",
  defaultConfig,
  createApi: () => {
    const names = new Map<string, string>();
    return { names, messageTypeName: (messageId) => names.get(messageId) };
  },
  async handler(plugin) {
    const { schemas, messages: messageKeys } = asyncapiSchemas(
      plugin.document,
      plugin.config.messageSuffix,
    );

    const [context] = await createClient({
      // why: stop Hey API from merging in an `openapi-ts.config.*` from the cwd.
      configFile: "ir-kit-asyncapi-no-config.none",
      dryRun: true,
      input: {
        openapi: "3.1.0",
        info: { title: "asyncapi", version: "0" },
        paths: {},
        components: { schemas },
      },
      logs: { file: false, level: "silent" },
      // why: Hey API empties `output.path` even on a dry run.
      output: {
        clean: false,
        fileName: { case: "preserve", suffix: ".gen" },
        header: HEADER,
        path: ".",
      },
      plugins: ["@hey-api/typescript"],
    });
    if (!context) throw new Error("@hey-api/openapi-ts produced no output");

    for (const [messageId, key] of messageKeys) {
      const [symbol] = context.gen.symbols.query({
        resource: "definition",
        resourceId: schemaRef(key),
      });
      if (symbol) plugin.api.names.set(messageId, symbol.finalName);
    }

    const types = [...context.gen.render()].find(
      (file) => basename(file.path) === "types.gen.ts",
    );
    if (!types) throw new Error("@hey-api/typescript emitted no types.gen.ts");
    plugin.emit({ path: "types.gen.ts", content: types.content });
  },
});

/** Hey API's symbol table holds the final (cased, de-duplicated) name of each message's type. */
interface MessageTypeRegistry extends TypescriptApi {
  names: Map<string, string>;
}
